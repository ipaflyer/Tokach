#!/usr/bin/env python3
import json
import os
import sys

event = json.load(sys.stdin)

# Loop выключен
if not os.path.exists(".cursor/LOOP_ON"):
    print("{}")
    sys.exit(0)

# Не продолжаем после ошибки/ручной остановки
if event.get("status") != "completed":
    print("{}")
    sys.exit(0)

# Agent решил, что цикл закончен
if os.path.exists(".cursor/LOOP_DONE"):
    if os.path.exists(".cursor/LOOP_ON"):
        os.remove(".cursor/LOOP_ON")

    print("{}")
    sys.exit(0)

iteration = event.get("loop_count", 0) + 1

prompt = f"""
GAMEPLAY ITERATION {iteration}

Продолжай автономный цикл разработки игры «Толкач».
Цель цикла — довести прототип до цельной playable-игры: сильный core gameplay + современный, красочный визуал.
Отвечай на русском.

Сначала прочитай:
- GAME_DESIGN.md
- PROTOTYPE_SPEC.md
- ITERATION_LOG.md, если он существует.

Затем:

1. Запусти текущую версию игры и проверь её состояние.
   Это HTML-прототип: подними локальный сервер при необходимости и обязательно используй Browser.
   Взаимодействуй с игрой (ходы A/B), сделай screenshot игрового состояния, при возможности смотри console logs.
   Оценивай не только код, но и фактическое поведение и ощущение от экрана.

2. Найди ОДНУ наиболее важную сейчас проблему:
   - blocking bug;
   - слабая обратная связь;
   - скучная часть core loop;
   - бессмысленное решение;
   - доминирующая стратегия;
   - отсутствие напряжения;
   - чрезмерная рутина;
   - визуал всё ещё «прототипный» / нечитаемый / несовременный (если gameplay уже держится).

3. Выбери изменение с максимальным ожидаемым влиянием.
   Приоритет: сначала gameplay, затем обратная связь и визуал, который усиливает решение игрока (тон, кража, закрытый тон, камень).

4. Реализуй его.
   Не расширяй scope.
   Не добавляй контент просто ради количества контента.
   Не добавляй обрыв/пятёрку/мета, пока гипотеза тона не подтверждена или явно не провалена по логу.

5. Снова запусти игру через Browser (screenshot) и/или самопроверки правил. Проверь результат.

6. Запиши в ITERATION_LOG.md:
   - что было не так;
   - что изменено;
   - почему;
   - результат проверки (включая что увидел в Browser);
   - что остаётся наиболее слабым местом.

7. Закончи эту итерацию.

Если считаешь, что критерии PROTOTYPE_SPEC.md выполнены, core loop держит внимание,
визуал читаемый и современный, а дальнейшие изменения без участия человека становятся
скорее субъективными, чем объективно полезными — создай файл .cursor/LOOP_DONE.

Не создавай LOOP_DONE только потому, что программа запускается.
Цель — проверить и улучшить core gameplay, затем довести ощущение игры (включая визуал).
"""

print(json.dumps({"followup_message": prompt}, ensure_ascii=False))
